#!/usr/bin/env python3
"""Generate src/emoji_table.rs from iamcal/emoji-data's emoji.json.

    python3 tools/gen_emoji.py [path/to/emoji.json]

With no path the current emoji.json is downloaded from GitHub. Slack's
emoji names are this project's `short_names` (Slack ships the same
data), so every short name becomes one row `(name, emoji)` where the
emoji is the fully-qualified sequence (`unified`, FE0F included): tmux
draws a variation-selector glyph two cells wide and that is what we
assume in the cell model. A skin-tone modifier is appended at lookup
time (see src/emoji.rs): for every single-modifier variation in the
data, the variant is the base's first scalar, a FE0F right after it
dropped, then the modifier, then the rest, and this script checks that
rule still holds so no second table is needed.

`simple_smile` is a Slack-only legacy name (the data lacks it): one
extra row to U+1F642.

Standard library only; the output is sorted by name (byte order, what
Rust's `&str` ordering and a binary search want).
"""

import json
import os
import sys
import urllib.request

URL = "https://raw.githubusercontent.com/iamcal/emoji-data/master/emoji.json"
EXTRA = {"simple_smile": "1F642"}
# Scalars with no glyph of their own: escaped so the row stays readable.
INVISIBLE = {0x200D, 0xFE0F, 0x20E3}


def load(path):
    if path:
        with open(path, "rb") as f:
            return json.load(f), path
    with urllib.request.urlopen(URL, timeout=60) as r:
        return json.load(r), URL


def to_str(unified):
    return "".join(chr(int(h, 16)) for h in unified.split("-"))


def rust_str(s):
    out = []
    for c in s:
        if c in '"\\':
            out.append("\\" + c)
        elif ord(c) < 0x20 or ord(c) in INVISIBLE:
            out.append("\\u{%X}" % ord(c))
        else:
            out.append(c)
    return '"' + "".join(out) + '"'


def check_skin_rule(data):
    bad = []
    for e in data:
        parts = e["unified"].split("-")
        for mod, var in (e.get("skin_variations") or {}).items():
            if "-" in mod:
                continue  # two-person variants: Slack has no single name for them
            rest = parts[1:]
            if rest and rest[0] == "FE0F":
                rest = rest[1:]
            guess = "-".join([parts[0], mod] + rest)
            if guess != var["unified"]:
                bad.append((e["short_name"], mod, var["unified"], guess))
    return bad


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else None
    data, source = load(path)
    bad = check_skin_rule(data)
    if bad:
        for b in bad:
            sys.stderr.write("skin rule broken: %s %s is %s, rule says %s\n" % b)
        sys.exit(1)
    rows = {}
    for e in data:
        for name in e["short_names"]:
            if name in rows and rows[name] != e["unified"]:
                sys.exit("duplicate short name %s" % name)
            rows[name] = e["unified"]
    for name, uni in EXTRA.items():
        rows.setdefault(name, uni)
    version = max((e.get("added_in", "0") for e in data), key=lambda v: [int(x) for x in v.split(".")])
    names = sorted(rows, key=lambda n: n.encode())
    here = os.path.dirname(os.path.abspath(__file__))
    out_path = os.path.join(here, "..", "src", "emoji_table.rs")
    with open(out_path, "w", encoding="utf-8") as out:
        out.write("//! Slack's emoji names -> the glyph. GENERATED by tools/gen_emoji.py,\n")
        out.write("//! do not edit: rerun the script instead.\n//!\n")
        out.write("//! Source: iamcal/emoji-data emoji.json (MIT), Emoji %s data,\n" % version)
        out.write("//! %d entries, %d names (plus %s).\n" % (len(data), len(rows) - len(EXTRA), ", ".join(sorted(EXTRA))))
        out.write("//! Read from %s.\n" % ("the GitHub master branch" if source == URL else os.path.basename(source)))
        out.write("//! Each glyph is the fully-qualified sequence (FE0F kept); a skin tone\n")
        out.write("//! is added by emoji::lookup. Sorted by name in byte order for a\n")
        out.write("//! binary search.\n\n")
        out.write("pub static TABLE: &[(&str, &str)] = &[\n")
        for n in names:
            out.write("    (%s, %s),\n" % (rust_str(n), rust_str(to_str(rows[n]))))
        out.write("];\n")
    sys.stderr.write("wrote %s: %d rows\n" % (os.path.normpath(out_path), len(rows)))


if __name__ == "__main__":
    main()
